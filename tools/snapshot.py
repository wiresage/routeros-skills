"""Describe the documentation snapshot that the skills were built from (docs-snapshot.json)."""

from __future__ import annotations

import collections
import json
import re
from pathlib import Path

import helpgap

MANUAL = "https://manual.mikrotik.com"
HELP = "https://help.mikrotik.com/docs"
NOT_INCLUDED = [
    {
        "what": "Blog posts and tag listing pages of manual.mikrotik.com",
        "why": "Product news, and index pages that only repeat links",
    },
    {
        "what": "Documentation change log of manual.mikrotik.com (/changelog)",
        "why": "Edit history of the manual, not RouterOS documentation",
    },
    {"what": "Pictures and diagrams", "why": "Not usable offline; every reference page links to its source page"},
    {
        "what": "Translations in the help.mikrotik.com quick guides",
        "why": "The English text is complete; other languages repeat it",
    },
    {
        "what": "Internal numeric enum codes in the CLI reference",
        "why": "Implementation detail that the console never asks for",
    },
]


def classify_help(
    cache: Path,
    help_pages: dict[str, dict],
    manual_pages: dict[str, dict],
    imported: set[str],
    excluded: dict[str, str],
    covered: dict[str, str],
) -> dict[str, tuple[str, str]]:
    """Run the help-gap rules against the whole manual (narrative pages, CLI pages, hardware manuals)."""
    titles = {helpgap.compact(r["title"]) for p, r in manual_pages.items() if not p.startswith("docs/cli-reference/")}
    for file in (cache / "manual" / "hardware").glob("*.json"):
        page = json.loads(file.read_text(encoding="utf-8"))
        titles.update({helpgap.compact(page["title"]), helpgap.compact(file.stem)})
    corpus: set[str] = set()
    for record in manual_pages.values():
        corpus |= helpgap.shingles((cache / "manual" / "pages" / record["path"]).read_text(encoding="utf-8"))
    return helpgap.classify(help_pages, titles, corpus, imported, excluded, covered)


def sitemap_counts(sitemap: Path) -> dict[str, int]:
    """Count sitemap URLs by area."""
    counts: collections.Counter[str] = collections.Counter()
    for url in re.findall(r"<loc>([^<]+)</loc>", sitemap.read_text(encoding="utf-8")):
        path = url[len(MANUAL) :].strip("/")
        if path.startswith("docs/tags"):
            counts["tag listing pages"] += 1
        elif path.startswith("changelog"):
            counts["documentation change log"] += 1
        elif path.startswith("blog"):
            counts["blog"] += 1
        elif path.startswith("hardware"):
            counts["hardware manuals"] += 1
        else:
            counts["documentation pages"] += 1
    return dict(sorted(counts.items()))


def write_snapshot(
    path: Path,
    cache: Path,
    manifest: dict,
    help_pages: dict[str, dict],
    statuses: dict[str, tuple[str, str]],
    skills: dict[str, dict],
    skill_stats: dict[str, dict[str, int]],
) -> None:
    pages = manifest["pages"]
    cli = sum(1 for r in pages if r["path"].startswith("docs/cli-reference/"))
    by_status = collections.Counter(status for status, _ in statuses.values())
    spaces = collections.Counter(p["space"] for p in help_pages.values())
    snapshot = {
        "_comment": "Generated by tools/build_references.py. Do not edit.",
        "manual": {
            "url": MANUAL,
            "crawled": manifest["crawled"],
            "index_entries": len(pages),
            "guides": len(pages) - cli,
            "cli_reference_pages": cli,
            "hardware_manuals": len(manifest["hardware"]),
            "sitemap_urls": sitemap_counts(cache / "manual" / "sitemap.xml"),
        },
        "help": {
            "url": HELP,
            "note": "Frozen by MikroTik; the manual replaced it. Only pages the manual lacks are used.",
            "pages_crawled": len(help_pages),
            "pages_by_space": dict(sorted(spaces.items())),
            "imported": by_status["imported"],
            "covered_by_manual": by_status["covered"],
            "excluded": by_status["excluded"],
            "excluded_pages": {
                page_id: {"title": help_pages[page_id]["title"], "reason": detail}
                for page_id, (status, detail) in sorted(statuses.items())
                if status == "excluded"
            },
        },
        "not_included": NOT_INCLUDED,
        "skills": {name: {"title": skills[name]["title"], **skill_stats.get(name, {})} for name in sorted(skills)},
    }
    path.write_text(json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
